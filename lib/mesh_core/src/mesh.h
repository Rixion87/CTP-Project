/*mesh.h*/


#pragma once
#include "radioHAL.h"
#include "packet.h"
#include "routing.h"
#include "seenCache.h"

class MeshNode {
    RadioHAL*       _radio;
    RoutingTable    _routes;
    SeenCache       _seen;
    uint16_t        _nodeID;
    uint8_t         _seqNum = 0;

public:
    MeshNode(RadioHAL* radio, uint16_t nodeID)
        : _radio(radio), _nodeID(nodeID) {}
        
    void begin() {
        _radio->begin();
    }


    /*Send a packet originating from this node*/
    void sendMessage(uint16_t destID, const char* text) {
        MeshPacket pkt; 
        pkt.version     = PROTO_VERSION;
        pkt.type        = PKT_MESSAGE;
        pkt.srcID       = _nodeID;
        pkt.destID      = destID;
        pkt.ttl         = MAX_TTL;
        pkt.seqNum      = _seqNum++;
        pkt.payloadLen  = strlen(text);
        memcpy(pkt.payload, text, pkt.payloadLen);

        _seen.markSeen(_nodeID, pkt.seqNum); /*prevents from relaying packets being generated by this node*/
        transmit(pkt);
    }

    void update() {
        uint8_t buf[sizeof(MeshPacket)];
        int16_t len = _radio->receive(buf, sizeof(buf));
        if (len < HEADER_LEN) 
            return;
        MeshPacket* pkt = (MeshPacket*)buf;

        /*Drop any duplicate packets*/
        if (_seen.hasSeen(pkt->srcID, pkt->seqNum)) 
            return;
        _seen.markSeen(pkt->srcID, pkt->seqNum);

        /*Update routing table*/
        _routes.update(pkt->srcID, MAX_TTL - pkt->ttl, _radio->getRSSI());

        /*Check if packet is addressed to us*/
        if (pkt->destID == _nodeID || pkt->destID == BROADCAST_ADDR) {
            onReceive(*pkt);
        }

        /*Relay if TTL allows*/
        if (pkt->ttl > 1 && pkt->destID != _nodeID) {
            pkt->ttl--;
            transmit(*pkt);
        }
    }

private: 
    void transmit(const MeshPacket& pkt) {
        uint16_t wireLen = HEADER_LEN + pkt.payloadLen + MIC_LEN;
        _radio->send((uint8_t*)&pkt, wireLen);    
    }

    void onReceive(const MeshPacket& pkt) {
        char buf[64];
        sniprintf(buf, sizeof(buf),
            "[MSG] From 0x%04X -> 0x%04X: %.*s\n",
            pkt.srcID, pkt.destID,
            pkt.payloadLen, pkt.payload);   
        Serial.println(buf);
    }






};